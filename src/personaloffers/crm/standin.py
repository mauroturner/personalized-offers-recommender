"""The stand-in of the CRM: the API of the plan over SQLite (RF15, RF23; AC19, AC20; plan section 18; decisions D25, D27; risk items 2 and 3).

``standin_app(db_path, token)`` is a FastAPI application with four routes and nothing else:

* ``PUT /api/v1/rounds/<round>/offers`` takes ``{"contacts": [{"contact_id": n, "offers": [{"rank": 1, "stock_code": "85123A", "source": "repeat"}, ...]}]}`` (at most ``batch_size`` contacts and
  ``max_body_bytes`` bytes) and answers 200 ``{"created", "unchanged"}``: a contact that has no list in that round gets it, one that has the very same list is ``unchanged``. A contact that has *another* list
  is 409 ``list_conflict`` for the whole batch and **nothing of it is applied**: a list that was issued does not change, and the database refuses an update or a delete itself (two triggers);
* ``GET /api/v1/rounds/<round>/offers?offset=&limit=`` reads the round by pages in the order of the contact, ``{"data": [...], "total": n}``; ``limit`` is at most ``batch_size``;
* ``GET /api/v1/contacts/<contact>/offers?round_id=`` reads one list, 404 when the contact has none;
* ``GET /health``, ``{"status": "ok"}``.

**The token** is asked for before the route is looked at: every request needs ``Authorization: Bearer <token>``, compared with ``hmac.compare_digest``, and anything else, a route that does not exist
included, is 401 with ``WWW-Authenticate: Bearer``. Without a token the application does not start. **An error is one fixed word** (``unauthorized``, ``not_found``, ``bad_request``,
``payload_too_large``, ``list_conflict``, ``internal_error``): never a path, a query, a trace or what was sent. A round that does not look like ``R<year>-<month>-<day>`` is 404 before the database is
opened; there is no documentation page and no schema; the body is read in pieces and counted, so a stream that goes past the limit is cut whatever it says its length is.

A stand-in is not a CRM: it is the CRM of the suite and of the quick mode, with the shape the flow needs (idempotence for a batch that is sent again, a conflict that is not applied, a read back that
pages). The real one answers the smoke test that the owner runs against the tool they choose (D25).
"""

from __future__ import annotations

import hmac
import json
import os
import re
import sqlite3
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from fastapi import FastAPI, Request, Response
from fastapi.concurrency import run_in_threadpool

ROUND = re.compile(r"R[0-9]{4}-[0-9]{2}-[0-9]{2}")
STOCK_CODE = re.compile(r"[A-Za-z0-9]{1,12}")
SOURCES = ("repeat", "discovery", "fallback")
MAX_OFFERS = 50                    # a list of a contact: the plan has 10, the stand-in takes up to this many
MAX_CONTACT_ID = 2**53 - 1         # what a JSON number holds exactly
MAX_DIGITS = 16
CODES = {"unauthorized": 401, "not_found": 404, "bad_request": 400, "payload_too_large": 413, "list_conflict": 409, "internal_error": 500}
SCHEMA = (
    "CREATE TABLE IF NOT EXISTS lists (round_id TEXT NOT NULL, contact_id INTEGER NOT NULL, offers TEXT NOT NULL, PRIMARY KEY (round_id, contact_id)) WITHOUT ROWID",
    "CREATE TRIGGER IF NOT EXISTS lists_no_update BEFORE UPDATE ON lists BEGIN SELECT RAISE(ABORT, 'lists es de solo inserción: una lista emitida no se cambia'); END",
    "CREATE TRIGGER IF NOT EXISTS lists_no_delete BEFORE DELETE ON lists BEGIN SELECT RAISE(ABORT, 'lists es de solo inserción: una lista emitida no se borra'); END",
    "CREATE TRIGGER IF NOT EXISTS lists_no_replace BEFORE INSERT ON lists WHEN EXISTS (SELECT 1 FROM lists WHERE round_id = NEW.round_id AND contact_id = NEW.contact_id) "
    "BEGIN SELECT RAISE(ABORT, 'lists es de solo inserción: esa lista ya se emitió'); END",
)


class Fault(Exception):
    """An error the stand-in answers with one of ``CODES``."""

    def __init__(self, code: str) -> None:
        super().__init__(code)
        self.code = code


def _reply(status: int, payload: Any, headers: Mapping[str, str] | None = None) -> Response:
    return Response(content=json.dumps(payload, separators=(",", ":"), ensure_ascii=False), status_code=status, media_type="application/json", headers=dict(headers or {}))


def _error(code: str) -> Response:
    return _reply(CODES[code], {"code": code}, {"WWW-Authenticate": "Bearer"} if code == "unauthorized" else None)


# --- the database --------------------------------------------------------------------------------------------------------------


def _connect(path: Path) -> sqlite3.Connection:
    conn = sqlite3.connect(path, isolation_level=None, timeout=30)
    conn.execute("PRAGMA journal_mode=DELETE")
    conn.execute("PRAGMA synchronous=NORMAL")   # a stand-in is regenerated by the replay: atomic (rollback journal), not guaranteed to survive a power cut
    return conn


def _canonical(offers: list[dict[str, Any]]) -> str:
    return json.dumps(sorted(offers, key=lambda offer: offer["rank"]), sort_keys=True, separators=(",", ":"))


def _int_in(value: Any, low: int, high: int) -> int:
    if type(value) is not int or not low <= value <= high:
        raise Fault("bad_request")
    return value


def _exact_keys(item: Any, keys: set[str]) -> dict[str, Any]:
    if not isinstance(item, dict) or set(item) != keys:
        raise Fault("bad_request")
    return item


def _offers_of(raw: Any) -> list[dict[str, Any]]:
    if not isinstance(raw, list) or not 1 <= len(raw) <= MAX_OFFERS:
        raise Fault("bad_request")
    found = []
    for position, item in enumerate(raw, start=1):
        offer = _exact_keys(item, {"rank", "stock_code", "source"})
        code, source = offer["stock_code"], offer["source"]
        if _int_in(offer["rank"], 1, MAX_OFFERS) != position or not isinstance(code, str) or not STOCK_CODE.fullmatch(code) or source not in SOURCES:
            raise Fault("bad_request")
        found.append({"rank": position, "stock_code": code, "source": source})
    if len({offer["stock_code"] for offer in found}) != len(found):
        raise Fault("bad_request")
    return found


def _contacts_of(body: Any, batch_size: int) -> list[tuple[int, str]]:
    """The ``(contact_id, canonical offers)`` of a batch, validated: the keys are exactly the plan's, the ranks run 1, 2, 3... in order, a product and a contact appear once."""
    document = _exact_keys(body, {"contacts"})
    raw = document["contacts"]
    if not isinstance(raw, list) or not 1 <= len(raw) <= batch_size:
        raise Fault("bad_request")
    found = []
    for item in raw:
        contact = _exact_keys(item, {"contact_id", "offers"})
        found.append((_int_in(contact["contact_id"], 1, MAX_CONTACT_ID), _canonical(_offers_of(contact["offers"]))))
    if len({contact_id for contact_id, _ in found}) != len(found):
        raise Fault("bad_request")
    return found


def _apply(db_path: Path, round_id: str, contacts: list[tuple[int, str]]) -> dict[str, int]:
    """Create what is not there and count what is the same; one list that differs refuses the whole batch (nothing is written)."""
    conn = _connect(db_path)
    try:
        conn.execute("BEGIN IMMEDIATE")
        try:
            stored = {contact_id: offers for contact_id, offers in conn.execute(f"SELECT contact_id, offers FROM lists WHERE round_id = ? AND contact_id IN ({', '.join('?' * len(contacts))})",
                                                                                 [round_id, *(contact_id for contact_id, _ in contacts)])}
            if any(contact_id in stored and stored[contact_id] != offers for contact_id, offers in contacts):
                raise Fault("list_conflict")
            fresh = [(round_id, contact_id, offers) for contact_id, offers in contacts if contact_id not in stored]
            conn.executemany("INSERT INTO lists (round_id, contact_id, offers) VALUES (?, ?, ?)", fresh)
            conn.execute("COMMIT")
        except BaseException:
            if conn.in_transaction:
                conn.execute("ROLLBACK")
            raise
        return {"created": len(fresh), "unchanged": len(contacts) - len(fresh)}
    finally:
        conn.close()


def _page(db_path: Path, round_id: str, offset: int, limit: int) -> dict[str, Any]:
    conn = _connect(db_path)
    try:
        total = conn.execute("SELECT COUNT(*) FROM lists WHERE round_id = ?", (round_id,)).fetchone()[0]
        rows = conn.execute("SELECT contact_id, offers FROM lists WHERE round_id = ? ORDER BY contact_id LIMIT ? OFFSET ?", (round_id, limit, offset)).fetchall()
        return {"data": [{"contact_id": contact_id, "offers": json.loads(offers)} for contact_id, offers in rows], "total": total}
    finally:
        conn.close()


def _one(db_path: Path, round_id: str, contact_id: int) -> dict[str, Any]:
    conn = _connect(db_path)
    try:
        row = conn.execute("SELECT offers FROM lists WHERE round_id = ? AND contact_id = ?", (round_id, contact_id)).fetchone()
    finally:
        conn.close()
    if row is None:
        raise Fault("not_found")
    return {"contact_id": contact_id, "offers": json.loads(row[0])}


def _number(request: Request, name: str, default: int, low: int, high: int) -> int:
    raw = request.query_params.get(name)
    if raw is None:
        return default
    if not (raw.isascii() and raw.isdigit()) or len(raw) > MAX_DIGITS:
        raise Fault("bad_request")
    return _int_in(int(raw), low, high)


async def _body(request: Request, limit: int) -> bytes:
    """The body, read in pieces and counted: more than `limit` bytes is ``payload_too_large`` whatever ``Content-Length`` says (or does not say)."""
    declared = request.headers.get("content-length", "")
    if declared.isascii() and declared.isdigit() and int(declared) > limit:
        raise Fault("payload_too_large")
    received = bytearray()
    async for chunk in request.stream():
        received += chunk
        if len(received) > limit:
            raise Fault("payload_too_large")
    return bytes(received)


# --- the application ---------------------------------------------------------------------------------------------------------


def standin_app(db_path: Path, token: str | None, *, batch_size: int = 500, max_body_bytes: int = 2_000_000) -> FastAPI:
    """The stand-in over the SQLite file `db_path` (created with its folder) that answers only to ``Authorization: Bearer <token>``. Without a token it does not start (and creates nothing)."""
    if not isinstance(token, str) or not token.strip():
        raise ValueError("el sustituto del CRM necesita un token (sin él no arranca)")
    if batch_size < 1 or max_body_bytes < 1:
        raise ValueError("batch_size y max_body_bytes deben ser al menos 1")
    expected = f"Bearer {token}".encode()
    db_path = Path(db_path)
    db_path.parent.mkdir(parents=True, exist_ok=True)
    setup = _connect(db_path)
    try:
        for statement in SCHEMA:
            setup.execute(statement)
    finally:
        setup.close()
    app = FastAPI(docs_url=None, redoc_url=None, openapi_url=None)

    @app.middleware("http")
    async def authenticate(request: Request, call_next):
        supplied = request.headers.get("authorization", "").encode()
        if not hmac.compare_digest(supplied, expected):
            return _error("unauthorized")
        return await call_next(request)

    @app.exception_handler(Fault)
    async def fault(request: Request, error: Fault):
        return _error(error.code)

    @app.exception_handler(Exception)
    async def crash(request: Request, error: Exception):
        return _error("internal_error")

    def known(round_id: str) -> str:
        if not ROUND.fullmatch(round_id):
            raise Fault("not_found")
        return round_id

    @app.get("/health")
    def health() -> Response:
        return _reply(200, {"status": "ok"})

    @app.put("/api/v1/rounds/{round_id}/offers")
    async def put_offers(round_id: str, request: Request) -> Response:
        known(round_id)
        raw = await _body(request, max_body_bytes)
        try:
            contacts = _contacts_of(json.loads(raw), batch_size)
        except (ValueError, RecursionError):
            raise Fault("bad_request") from None
        return _reply(200, await run_in_threadpool(_apply, db_path, round_id, contacts))

    @app.get("/api/v1/rounds/{round_id}/offers")
    async def read_round(round_id: str, request: Request) -> Response:
        known(round_id)
        offset, limit = _number(request, "offset", 0, 0, MAX_CONTACT_ID), _number(request, "limit", batch_size, 1, batch_size)
        return _reply(200, await run_in_threadpool(_page, db_path, round_id, offset, limit))

    @app.get("/api/v1/contacts/{contact_id}/offers")
    async def read_contact(contact_id: str, request: Request) -> Response:
        if not (contact_id.isascii() and contact_id.isdigit()) or len(contact_id) > MAX_DIGITS or not 1 <= int(contact_id) <= MAX_CONTACT_ID:
            raise Fault("not_found")
        round_id = request.query_params.get("round_id")
        if round_id is None:
            raise Fault("bad_request")
        known(round_id)
        return _reply(200, await run_in_threadpool(_one, db_path, round_id, int(contact_id)))

    @app.api_route("/{path:path}", methods=["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"])
    def nothing_else(path: str) -> Response:
        """Whatever is not one of the routes above, whatever its method, is the same 404 that says nothing of the path."""
        return _error("not_found")

    return app


def create_app(cfg: Any, env: Mapping[str, str] | None = None) -> FastAPI:
    """The stand-in of a configuration: the file of ``[paths] crm_db``, the limits of ``[crm]`` and the token of the variable ``[crm] token_env`` names in `env` (the process's by default). Without the
    token it does not start."""
    environment = os.environ if env is None else env
    return standin_app(cfg.paths.crm_db, environment.get(cfg.crm.token_env), batch_size=cfg.crm.batch_size, max_body_bytes=cfg.crm.max_body_bytes)


def create_app_from_environment() -> FastAPI:
    """The stand-in of the process: the configuration of ``$PERSONALOFFERS_CONFIG`` (or the default one) and the token of its variable. What uvicorn's ``--factory`` calls in the ``crm`` service of the
    compose file (D26); without the token it does not start."""
    from personaloffers import config as config_module

    return create_app(config_module.load_config())
